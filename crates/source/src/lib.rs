//! Граница источника наблюдений.
//!
//! Коннектор — крейт, реализующий этот трейт; набор коннекторов собирается
//! фичами под конкретную систему ([ADR-0004](../../../docs/adr/0004-connectors-as-features.md)).
//! Ядро агента знает только трейт и не знает ни одного коннектора по имени.
//!
//! Граница нарочно узкая: снять бакеты за промежуток минут — всё, что агенту
//! нужно от источника для наблюдения. Чем меньше здесь методов, тем дешевле
//! добавить пятый источник и тем проще спрятать за этой границей внешний
//! процесс, если такое когда-нибудь понадобится.

use std::time::Duration;

use async_trait::async_trait;
use autosre_domain::{Bucket, Span, Stream};

/// Отказы источника.
///
/// Причины описаны строками: крейт границы не должен тащить за собой ни
/// HTTP-клиент, ни драйвер базы — иначе их потянет каждый, кто эту границу
/// пересекает.
///
/// Имени источника здесь нет намеренно: тот, кто вызвал, и так знает, кого
/// спрашивал, а повторять это в каждой ошибке — лишний шум.
#[derive(Debug, thiserror::Error)]
pub enum SourceError {
    #[error("источник недоступен: {0}")]
    Transport(String),
    #[error("источник ответил {status}: {body}")]
    Status { status: u16, body: String },
    #[error("ответ источника не разобран: {0}")]
    Shape(String),
    #[error("источник не исполняет произвольных запросов")]
    Unsupported,
}

/// Источник наблюдений: логи, метрики, дальше — прочие.
#[async_trait]
pub trait Source: Send + Sync {
    /// Имя, под которым источник виден в базе, журнале и метриках.
    fn name(&self) -> &str;

    /// Снимает бакеты за промежуток минут.
    ///
    /// Число запросов к источнику не зависит ни от числа потоков, ни от длины
    /// промежутка: агрегирует источник, а не агент.
    ///
    /// # Errors
    /// [`SourceError`] при недоступности источника или неожиданной форме ответа.
    async fn buckets(&self, span: Span) -> Result<Vec<Bucket>, SourceError>;

    /// Живые записи потока за промежуток — то, из чего считается сигнатура.
    ///
    /// У источника метрик записей нет: значение и есть всё, что он знает.
    /// Поэтому по умолчанию пусто, а не «не поддерживается»: отсутствие
    /// образцов — обычное дело, а не отказ.
    ///
    /// # Errors
    /// [`SourceError`] при недоступности источника.
    async fn samples(
        &self,
        _stream: &Stream,
        _span: Span,
        _limit: usize,
    ) -> Result<Vec<String>, SourceError> {
        Ok(Vec::new())
    }

    /// Произвольный запрос на языке источника — то, что написал автор скилла
    /// ([ADR-0005](../../../docs/adr/0005-native-queries.md)).
    ///
    /// Подстановки уже сделаны: сюда приходит готовый текст. Ответ — строки,
    /// по одной на запись, в виде, годном для чтения моделью. Промежуток нужен
    /// источнику, у которого запрос отвечает на момент, а не на отрезок.
    ///
    /// По умолчанию отказ, а не пустота: скилл с запросом к источнику, который
    /// запросов не исполняет, обязан об этом узнать.
    ///
    /// # Errors
    /// [`SourceError::Unsupported`], если источник запросов не исполняет;
    /// прочие [`SourceError`] при отказе источника.
    async fn query(
        &self,
        _text: &str,
        _span: Span,
        _limit: usize,
    ) -> Result<Vec<String>, SourceError> {
        Err(SourceError::Unsupported)
    }
}

/// Код ответа, за которым стоит занятость, а не отказ: шлюз без свободных
/// мест, прокси без живого бэкенда. Такое проходит само.
#[must_use]
pub fn busy(status: u16) -> bool {
    matches!(status, 429 | 502 | 503 | 504)
}

/// Повторяет действие по расписанию пауз, пока отказ проходящий.
///
/// Живёт здесь, а не в каждом клиенте: у логов, метрик и модели одна и та же
/// беда — обрыв связи и занятой шлюз, — и одно и то же лекарство. Что считать
/// проходящим, решает вызывающий: он видит и код ответа, и причину обрыва.
/// Отказ, который повторять незачем — таймаут, неверная схема, — отдаётся
/// сразу.
///
/// Решение о повторе принимает `passing` по каждому результату, включая
/// удачный: у HTTP-клиента «удача» — это ответ, а занятой шлюз отвечает
/// исправно. Число попыток — на одну больше числа пауз. Отдаёт последний
/// результат.
///
/// # Errors
/// Отказ последней попытки, если ни одна не удалась.
pub async fn again<T, E, Fut>(
    pauses: &[Duration],
    passing: impl Fn(&Result<T, E>) -> bool,
    mut act: impl FnMut() -> Fut,
) -> Result<T, E>
where
    Fut: Future<Output = Result<T, E>>,
{
    let mut got = act().await;
    for pause in pauses {
        if !passing(&got) {
            return got;
        }
        tracing::debug!(
            pause = pause.as_millis(),
            "отказ проходящий, повтор после паузы"
        );
        tokio::time::sleep(*pause).await;
        got = act().await;
    }
    got
}
