//! Граница источника наблюдений.
//!
//! Коннектор — крейт, реализующий этот трейт; набор коннекторов собирается
//! фичами под конкретную систему ([ADR-0004](../../../docs/adr/0004-connectors-as-features.md)).
//! Ядро агента знает только трейт и не знает ни одного коннектора по имени.
//!
//! Граница нарочно узкая: снять бакеты за промежуток минут — всё, что агенту
//! нужно от источника для наблюдения. Чем меньше здесь методов, тем дешевле
//! добавить пятый источник и тем проще спрятать за этой границей внешний
//! процесс, если такое когда-нибудь понадобится.

use async_trait::async_trait;
use sre_domain::{Bucket, Span};

/// Отказы источника.
///
/// Причины описаны строками: крейт границы не должен тащить за собой ни
/// HTTP-клиент, ни драйвер базы — иначе их потянет каждый, кто эту границу
/// пересекает.
///
/// Имени источника здесь нет намеренно: тот, кто вызвал, и так знает, кого
/// спрашивал, а повторять это в каждой ошибке — лишний шум.
#[derive(Debug, thiserror::Error)]
pub enum SourceError {
    #[error("источник недоступен: {0}")]
    Transport(String),
    #[error("источник ответил {status}: {body}")]
    Status { status: u16, body: String },
    #[error("ответ источника не разобран: {0}")]
    Shape(String),
}

/// Источник наблюдений: логи, метрики, дальше — прочие.
#[async_trait]
pub trait Source: Send + Sync {
    /// Имя, под которым источник виден в базе, журнале и метриках.
    fn name(&self) -> &str;

    /// Снимает бакеты за промежуток минут.
    ///
    /// Число запросов к источнику не зависит ни от числа потоков, ни от длины
    /// промежутка: агрегирует источник, а не агент.
    ///
    /// # Errors
    /// [`SourceError`] при недоступности источника или неожиданной форме ответа.
    async fn buckets(&self, span: Span) -> Result<Vec<Bucket>, SourceError>;
}
