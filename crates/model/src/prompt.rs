//! Промпты и подготовка данных для модели.

use sre_domain::{Deviation, Group};

/// Системный промпт отсева.
///
/// Короткий намеренно: отсев зовётся на каждое отклонение, и его цена должна
/// оставаться в сотнях токенов, а не в тысячах.
pub const SIFTER: &str = "Ты — Auto SRE, дежурный инженер. \
Тебе дают отклонение в логах или метриках: числа и самые частые сигнатуры. \
Ответь, стоит ли тратить на него разбор. \
Не стоит: привычный шум, ночные выгрузки, регулярные всплески по расписанию, \
незначительные колебания. Стоит: то, чего в норме не бывает, и то, что растёт. \
Сомневаешься — отвечай, что стоит: пропустить беду дороже, чем разобрать лишнее. \
Причину уложи в одну фразу по-русски.";

/// Отклонение в виде, пригодном для чтения моделью.
///
/// Сырые строки лога сюда не попадают: только сигнатуры со счётчиками.
#[must_use]
pub fn about(deviation: &Deviation, service: &str, groups: &[Group]) -> String {
    let signatures = if groups.is_empty() {
        "  (образцов нет: это метрика, а не логи)".to_owned()
    } else {
        groups
            .iter()
            .map(|group| format!("  {} × {}", group.count, group.signature.as_str()))
            .collect::<Vec<_>>()
            .join("\n")
    };
    format!(
        "Сервис: {service}\n\
         Источник: {}, горизонт: {}\n\
         Значение за окно: {:.0}, обычно: {:.0}, отклонение: {}\n\
         Частые сигнатуры окна:\n{signatures}",
        deviation.source,
        deviation.horizon,
        deviation.value,
        deviation.baseline,
        spread(deviation.score),
    )
}

/// Отклонение словами: ровная история даёт бесконечную оценку.
fn spread(score: f64) -> String {
    if score.is_finite() {
        format!("{score:.1} σ (робастных)")
    } else if score.is_sign_negative() {
        "такого низкого не бывало".to_owned()
    } else {
        "такого высокого не бывало".to_owned()
    }
}
